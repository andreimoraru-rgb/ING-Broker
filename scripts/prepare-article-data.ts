import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { articles, consolidatedLifeSlugs, withdrawnArticleSlugs, type Article } from '../src/data/articles';
const release = JSON.parse(readFileSync('src/data/translation-release.json', 'utf8')) as string[];
// Full article bodies are separate lazy modules. Only reviewed translations enter
// the approved set; unfinished locale pages retain their previous runtime content.
export function prepareArticleData() {
  const metadata: Record<string, Article[]> = {};
  const heldTranslations: string[] = [];
  for (const [lang, list] of Object.entries(articles)) {
    mkdirSync(`src/data/article-content-published/${lang}`, { recursive: true });
    metadata[lang] = list.map(article => {
      const path = `src/data/article-content/${lang}/${article.slug}.json`;
      let override = lang === 'ro' ? article : (release as string[]).includes(`${lang}/${article.slug}`) && existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null;
      if (lang !== 'ro' && override) {
        const original = articles.ro.find(a => a.slug === article.slug)!;
        const words = String(override.content || '').replace(/<[^>]*>/g, ' ').trim().split(/\s+/).length;
        const headings = (String(override.content || '').match(/<h2\b/gi) || []).length;
        // The word threshold is the owner's editorial acceptance criterion,
        // not a claim about Google's ranking algorithm. Hold incomplete drafts.
        if (override.reviewStatus !== 'approved' || words < 1500 || headings < (original.content.match(/<h2\b/gi) || []).length || /[\u2013\u2014]/.test(JSON.stringify(override))) {
          heldTranslations.push(`${lang}/${article.slug}`);
          override = null;
        }
      }
      const resolved: Article = { ...article, ...override, id: article.id, slug: article.slug, image: article.image, heroImage: article.heroImage, date: article.date, preserveLegacyLayout: lang === 'ro' ? article.preserveLegacyLayout : true };
      if (override) writeFileSync(`src/data/article-content-published/${lang}/${article.slug}.json`, JSON.stringify(resolved));
      // Preserve the old body for incomplete locales, without declaring approval.
      if (!override) {
        const fallback = `src/data/article-content-legacy/${lang}`;
        mkdirSync(fallback, { recursive: true });
        writeFileSync(`${fallback}/${article.slug}.json`, JSON.stringify(resolved));
      }
      return { ...resolved, content: '' };
    });
  }
  console.log(JSON.stringify({ heldTranslations, approvedTranslations: Object.entries(metadata).filter(([lang]) => lang !== 'ro').flatMap(([, list]) => list.filter(a => a.reviewStatus === 'approved')).length }));
  writeFileSync('src/data/articleMetadata.ts', `// Generated by the sitemap/build preflight. Do not hand-edit.\nimport type { Article } from './articles';\nexport const articles: Record<string, Article[]> = ${JSON.stringify(metadata)};\nexport const consolidatedLifeSlugs = new Set<string>(${JSON.stringify([...consolidatedLifeSlugs])});\nexport const withdrawnArticleSlugs = new Set<string>(${JSON.stringify([...withdrawnArticleSlugs])});\n`);
  return metadata;
}
